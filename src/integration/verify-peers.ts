import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Which dependencies the *user's project* must declare.
 *
 * `shirones` bundles everything it can, so this list is deliberately short: a
 * package appears here only when something resolves it from the project root
 * rather than from inside the installed package. There are three distinct
 * mechanisms, each verified rather than assumed:
 *
 * 1. `astro` — the project *is* an Astro project; its own `astro.config.mjs`
 *    imports it, and every Astro integration is loaded through it.
 * 2. `svelte` + `@astrojs/svelte` — `@astrojs/svelte` registers `svelte/*` and
 *    `@astrojs/svelte/client.js` in `optimizeDeps.include`, which Vite resolves
 *    from the **project root**. Missing either one leaves Svelte islands
 *    unhydrated while the page still renders, so the failure is silent.
 * 3. `sharp` — Astro's image service `import`s it dynamically from its own
 *    location, which never reaches the theme's nested `node_modules`, and its
 *    `@img/*` native bindings must be version-matched to the JS wrapper.
 *
 * The `@iconify-json/*` sets used to be a fourth entry: `astro-icon` located
 * them by reading the *user's* `package.json`, which made them unshippable no
 * matter how well the files resolved. The theme no longer uses astro-icon —
 * `Icon.svelte` consumes a collection generated by
 * `vite/icon/collections.ts`, which resolves from inside the installed package
 * — so those sets ship as ordinary dependencies and the user declares none of
 * them. That removed four lines from every user's `package.json`; this list is
 * what records why the rest cannot follow.
 *
 * The ranges come from the theme's own `package.json` so they cannot drift;
 * only the *tier* is declared here, because only the theme can say which of
 * these a build actually needs.
 */

/**
 * `runtime` — the build or dev server cannot work without it. A missing one is
 * an error, because it fails later as a cryptic resolution error.
 * `tooling` — only `astro check` and editor tooling need it. `astro build` and
 * `astro dev` succeed without it, so a missing one is a warning.
 */
export type PeerTier = "runtime" | "tooling";

export interface PeerRequirement {
	name: string;
	tier: PeerTier;
	/** Why this one cannot ship inside the theme. Shown with the error. */
	reason: string;
}

export const PEER_REQUIREMENTS: readonly PeerRequirement[] = [
	{
		name: "astro",
		tier: "runtime",
		reason: "the project's `astro.config.mjs` imports it",
	},
	{
		name: "svelte",
		tier: "runtime",
		reason:
			"`@astrojs/svelte` registers `svelte/*` in Vite's `optimizeDeps.include`, which is resolved from the project root",
	},
	{
		name: "@astrojs/svelte",
		tier: "runtime",
		reason:
			"registers its hydration client in `optimizeDeps.include`, so Svelte islands stay server-only without it",
	},
	{
		name: "sharp",
		tier: "runtime",
		reason:
			"Astro's image service imports it from the project root, and its native bindings must be version-matched",
	},
	{
		name: "@astrojs/check",
		tier: "tooling",
		reason: "only `astro check` needs it — `build` and `dev` do not",
	},
	{
		name: "typescript",
		tier: "tooling",
		reason: "only `astro check` needs it — `build` and `dev` do not",
	},
];

export interface PeerViolation {
	name: string;
	tier: PeerTier;
	reason: string;
	/** The range the theme needs, or null when it could not be determined. */
	required: string | null;
	/** What the project declares, or null when the dependency is absent. */
	declared: string | null;
	/** True when the dependency is present but its version is too old. */
	stale: boolean;
}

/** A dependency's version floor as [major, minor, patch], or null. */
function rangeFloor(range: unknown): [number, number, number] | null {
	if (typeof range !== "string") return null;
	const match = /(\d+)\.(\d+)(?:\.(\d+))?/.exec(range);
	if (!match) return null;
	return [Number(match[1]), Number(match[2]), Number(match[3] ?? 0)];
}

/** Whether floor `a` is strictly below floor `b`. Null floors are "unknown". */
function floorBelow(
	a: [number, number, number] | null,
	b: [number, number, number] | null,
): boolean {
	if (!a || !b) return false;
	for (let index = 0; index < 3; index += 1) {
		if (a[index] !== b[index]) return a[index] < b[index];
	}
	return false;
}

/**
 * `true` when the declared range cannot satisfy the required one.
 *
 * Ranges are compared by floor, which is what matters in practice: a caret
 * range that starts below the theme's floor will resolve to a version the
 * theme has never seen. A range with no numeric floor (`*`, `latest`,
 * `workspace:`) is taken as satisfying, since there is nothing to compare and
 * refusing to install is worse than a warning nobody can act on.
 */
function isStale(declared: unknown, required: unknown): boolean {
	return floorBelow(rangeFloor(declared), rangeFloor(required));
}

/** Turn `"pnpm add -D x@^1"` into something safe to paste into a shell. */
function installCommand(names: string[], ranges: Map<string, string>): string {
	const specs = names.map((name) => `${name}@${ranges.get(name) ?? "latest"}`);
	const manager = existsSync(join(process.cwd(), "pnpm-lock.yaml"))
		? "pnpm add -D"
		: "npm install -D";
	return `${manager} ${specs.join(" ")}`;
}

function readPackageJson(file: string): Record<string, unknown> | null {
	try {
		const parsed = JSON.parse(readFileSync(file, "utf8"));
		return typeof parsed === "object" && parsed !== null ? parsed : null;
	} catch {
		return null;
	}
}

/**
 * The ranges the theme needs, read from the package being run.
 *
 * `peerDependencies` is the published shape; `dependencies` and
 * `devDependencies` are the source-repo shape, where everything is declared
 * flat. Both are consulted so the same code works in either mode, and an
 * unparseable manifest simply yields no requirement rather than a crash.
 */
function requiredRanges(packageRoot: string): Map<string, string> {
	const pkg = readPackageJson(join(packageRoot, "package.json"));
	const sources = [
		pkg?.peerDependencies,
		pkg?.dependencies,
		pkg?.devDependencies,
	];
	const ranges = new Map<string, string>();
	for (const source of sources) {
		if (typeof source !== "object" || source === null) continue;
		for (const [name, range] of Object.entries(
			source as Record<string, unknown>,
		)) {
			if (typeof range === "string" && !ranges.has(name))
				ranges.set(name, range);
		}
	}
	return ranges;
}

export interface VerifyPeerRequirementsOptions {
	/** Absolute path to the installed theme, or the repo root in source mode. */
	packageRoot: string;
	/** Absolute path to the user's project root. */
	projectRoot: string;
	/**
	 * Skip the check entirely. Set for a theme repo checkout, whose own
	 * `node_modules` already satisfies everything.
	 */
	skip?: boolean;
}

/**
 * Compare the user's `package.json` against what the theme needs.
 *
 * Returns the violations in declaration order, runtime ones first. An empty
 * array means nothing to report.
 */
export function verifyPeerRequirements(
	options: VerifyPeerRequirementsOptions,
): PeerViolation[] {
	const { packageRoot, projectRoot, skip = false } = options;
	if (skip) return [];

	const project = readPackageJson(join(projectRoot, "package.json"));
	// No manifest yet means `shirones init` has not run here; the integration
	// already reports the missing configuration, so there is nothing to add.
	if (!project) return [];

	const declared = {
		...(typeof project.dependencies === "object" &&
		project.dependencies !== null
			? (project.dependencies as Record<string, unknown>)
			: {}),
		...(typeof project.devDependencies === "object" &&
		project.devDependencies !== null
			? (project.devDependencies as Record<string, unknown>)
			: {}),
	};
	const required = requiredRanges(packageRoot);

	const violations: PeerViolation[] = [];
	for (const requirement of PEER_REQUIREMENTS) {
		const range = required.get(requirement.name) ?? null;
		// No range means the theme cannot say what it needs — a manifest that
		// predates a dependency, or one that dropped it. Reporting "missing"
		// there would be a warning the user cannot act on.
		if (range === null) continue;
		const declaredRange = declared[requirement.name];
		if (typeof declaredRange === "string") {
			if (isStale(declaredRange, range)) {
				violations.push({
					name: requirement.name,
					tier: requirement.tier,
					reason: requirement.reason,
					required: range,
					declared: declaredRange,
					stale: true,
				});
			}
			continue;
		}
		violations.push({
			name: requirement.name,
			tier: requirement.tier,
			reason: requirement.reason,
			required: range,
			declared: null,
			stale: false,
		});
	}
	return violations;
}

/**
 * Report the violations through Astro's logger and return whether the build
 * should stop.
 *
 * pnpm already prints a peer-dependency warning, but it is generic — it names
 * the package and the wanted range and says nothing about why the range exists
 * or what to run. This is the version that tells the user what is missing, why
 * only the theme can know, and the exact command that fixes it.
 */
export function reportPeerViolations(
	violations: PeerViolation[],
	logger: { error: (message: string) => void; warn: (message: string) => void },
): boolean {
	if (violations.length === 0) return false;

	const runtime = violations.filter(
		(violation) => violation.tier === "runtime",
	);
	const tooling = violations.filter(
		(violation) => violation.tier === "tooling",
	);

	for (const violation of tooling) {
		const detail = violation.stale
			? `declares ${violation.declared}, the theme needs ${violation.required}`
			: "not declared";
		logger.warn(
			`${violation.name} ${detail} — ${violation.reason}. ` +
				"This only affects `astro check` and editor tooling; the build is unaffected.",
		);
	}

	if (runtime.length > 0) {
		const lines = runtime.map((violation) => {
			const detail = violation.stale
				? `declares ${violation.declared}, needs ${violation.required}`
				: "missing";
			return `  - ${violation.name} (${detail})\n    ${violation.reason}`;
		});
		const ranges = new Map(
			runtime.map((violation) => [
				violation.name,
				violation.required ?? "latest",
			]),
		);
		const command = installCommand(
			runtime.map((violation) => violation.name),
			ranges,
		);
		logger.error(
			`${runtime.length} required ${
				runtime.length === 1 ? "dependency is" : "dependencies are"
			} missing from this project:\n${lines.join("\n")}\n` +
				"  pnpm prints an unmet peer warning for these, but it does not say that the\n" +
				"  build will fail. Install them, or run `npx shirones init --update`:\n" +
				`    ${command}`,
		);
		return true;
	}
	return false;
}
